"""RFC 7807 Problem Details Data Model for HTTP APIs.

Denormalized from ARCHITECTURE_SPECIFICATION.md § 2.3.
"""
from datetime import datetime, timezone

from pydantic import BaseModel, Field


class InvalidParameter(BaseModel):
    """Validation failure detail for an individual parameter."""

    name: str = Field(..., description="Name of the invalid parameter or header")
    reason: str = Field(..., description="Explanation of validation failure")

class RFC7807ProblemDetails(BaseModel):
    """RFC 7807 compliant problem details object for Warden REST APIs."""

    type: str = Field(
        ...,
        description="URI reference identifying problem type",
    )
    title: str = Field(
        ...,
        description="Short human-readable summary of problem",
    )
    status: int = Field(
        ...,
        description="HTTP status code generated by origin server",
    )
    detail: str = Field(
        ...,
        description="Human-readable explanation specific to this occurrence",
    )
    instance: str = Field(
        ...,
        description="URI reference identifying specific occurrence (e.g. endpoint path)",
    )
    error_code: str = Field(
        ...,
        description="Internal enterprise error classification code",
    )
    invalid_parameters: list[InvalidParameter] | None = Field(
        default=None,
        description="List of specific parameter validation failures if applicable",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="ISO-8601 UTC timestamp of error generation",
    )
